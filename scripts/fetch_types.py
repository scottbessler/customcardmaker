#!/usr/bin/env python3
"""Regenerate public/type-data.js from Scryfall's public catalogs.

    python3 scripts/fetch_types.py

The type line editor suggests subtypes from these lists. They are game facts
(the Comprehensive Rules' lists of creature, land, artifact... types), fetched
once and committed rather than requested by the app: no request at runtime, no
build step, and a diff to review when a new set adds a type. Run it when one
does. https://scryfall.com/docs/api/catalogs
"""
import json
import sys
import urllib.request
from datetime import date
from pathlib import Path

CATALOGS = {
    "creature": "creature-types",
    "artifact": "artifact-types",
    "enchantment": "enchantment-types",
    "land": "land-types",
    "planeswalker": "planeswalker-types",
    "spell": "spell-types",
}
OUT = Path(__file__).resolve().parent.parent / "public" / "type-data.js"


def fetch(name: str) -> list[str]:
    request = urllib.request.Request(
        f"https://api.scryfall.com/catalog/{name}",
        headers={"Accept": "application/json", "User-Agent": "customcardmaker-dev/0.1"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return sorted(json.load(response)["data"], key=str.casefold)


def main() -> int:
    data = {key: fetch(name) for key, name in CATALOGS.items()}
    for key, values in data.items():
        if not values:
            print(f"{key}: Scryfall returned nothing; refusing to overwrite", file=sys.stderr)
            return 1
    body = ",\n".join(f"  {key}: {json.dumps(values, ensure_ascii=False)}" for key, values in data.items())
    OUT.write_text(
        f"// Generated by scripts/fetch_types.py from Scryfall's catalogs on {date.today()}.\n"
        f"// Do not edit by hand: change the script, or run it again.\n"
        f"export const TYPE_DATA = {{\n{body},\n}};\n"
    )
    print(f"wrote {OUT} ({', '.join(f'{k}: {len(v)}' for k, v in data.items())})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
